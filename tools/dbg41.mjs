import { readFileSync } from 'node:fs';
import * as THREE from 'three';
import { buildRigData, convMat } from '../js/rigdata.js';
import { RigEngine } from '../js/engine.js';
import { ThreeIkDelegate } from '../js/ikadapter.js';
const rigJson = JSON.parse(readFileSync(new URL('../data/rig.json', import.meta.url), 'utf8'));
const posesJson = JSON.parse(readFileSync(new URL('../data/poses2.json', import.meta.url), 'utf8'));
const rigData = buildRigData(rigJson);
const engine = new RigEngine(rigData, new ThreeIkDelegate());
const flat2m4 = f => new THREE.Matrix4().set(f[0],f[1],f[2],f[3],f[4],f[5],f[6],f[7],f[8],f[9],f[10],f[11],f[12],f[13],f[14],f[15]);
const pose = posesJson.poses.find(p=>p.name==='hand_L_back');
const rest = posesJson.poses.find(p=>p.name==='rest');
engine.resetBases(); engine.evaluate();
for (const [n,f] of Object.entries(pose.basis)) engine.setBasis(n, flat2m4(f));
const P = engine.evaluate();
const gt = n => convMat(flat2m4(pose.matrix[n]));
const gtr = n => convMat(flat2m4(rest.matrix[n]));
const V=THREE.Vector3;
const tailOf = (m, rec) => new V(0, rec.length, 0).applyMatrix4(m);
const heelRec = rigData.bones.get('hand_heel_ik.L');
const sockRec = rigData.bones.get('MCH-upper_arm_ik_target.L');
// COPY_LOCATION 语义: sock.p = sock.rest.p + (heel.tail_now - heel.tail_rest)
const myHeelTailNow = tailOf(P.get('hand_heel_ik.L'), heelRec);
const myHeelTailRest = tailOf(heelRec.rest, heelRec);
const predicted = new V().setFromMatrixPosition(sockRec.rest).add(new V().subVectors(myHeelTailNow, myHeelTailRest));
const gtHeelTailNow = tailOf(gt('hand_heel_ik.L'), heelRec);
const gtHeelTailRest = tailOf(gtr('hand_heel_ik.L'), heelRec);
const gtPredicted = new V().setFromMatrixPosition(gtr('MCH-upper_arm_ik_target.L')).add(new V().subVectors(gtHeelTailNow, gtHeelTailRest));
console.log('heel tail: mine-now =', myHeelTailNow.toArray().map(x=>+x.toFixed(3)), ' GT-now =', gtHeelTailNow.toArray().map(x=>+x.toFixed(3)));
console.log('heel tail: mine-rest=', myHeelTailRest.toArray().map(x=>+x.toFixed(3)), ' GT-rest=', gtHeelTailRest.toArray().map(x=>+x.toFixed(3)));
console.log('socket 我引擎输出:', new V().setFromMatrixPosition(P.get('MCH-upper_arm_ik_target.L')).toArray().map(x=>+x.toFixed(3)));
console.log('socket 预测(mine delta):', predicted.toArray().map(x=>+x.toFixed(3)));
console.log('socket GT 实际      :', new V().setFromMatrixPosition(gt('MCH-upper_arm_ik_target.L')).toArray().map(x=>+x.toFixed(3)));
console.log('socket 预测(GT delta):', gtPredicted.toArray().map(x=>+x.toFixed(3)));
console.log('GT socket 位移 vs rest =', new V().setFromMatrixPosition(gt('MCH-upper_arm_ik_target.L')).distanceTo(new V().setFromMatrixPosition(gtr('MCH-upper_arm_ik_target.L'))).toFixed(4));
console.log('GT heel tail 位移 vs rest =', gtHeelTailNow.distanceTo(gtHeelTailRest).toFixed(4));
